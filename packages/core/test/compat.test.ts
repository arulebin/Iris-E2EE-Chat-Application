/**
 * Compatibility with data written by the PRE-core web code.
 *
 * fixtures/legacy-web-v1.json was generated by running the old frontend modules
 * (frontend/src/crypto.ts, lib/atRest.ts, lib/messageStore.ts, lib/backup.ts,
 * lib/fingerprint.ts, lib/media.ts, lib/signal/*) at commit 9ce0fe1, before they moved
 * into @iris/core. Every case below reads those old blobs with the NEW code, on both
 * the WebCrypto provider and the pure-JS provider. Existing users' data must keep
 * opening: same keys, same blob layouts, same wire formats.
 */

describe.each(providers)('legacy web data, %s', (_name, makeProvider) => {
  describe('account crypto', () => {
    it('derives the same login credential (PBKDF2 600k then HKDF "iris-auth-v2")', async () => {
      setup(makeProvider())
      const { authKey } = await deriveCredentials(F.credentials.password, F.credentials.authSalt)
      expect(authKey).toBe(F.credentials.authKey)
    })

    it('unwraps a blob wrapped by the old wrapWithMaster', async () => {
      setup(makeProvider())
      const { master } = await deriveCredentials(F.credentials.password, F.credentials.authSalt)
      const pt = await unwrapWithMaster(master, F.wrapWithMaster.wrapped, F.wrapWithMaster.salt, F.wrapWithMaster.info)
      expect(toBase64(pt)).toBe(F.wrapWithMaster.plaintext)
    })

    it('rejects a wrong password with an OperationError', async () => {
      setup(makeProvider())
      const { master } = await deriveCredentials('wrong password', F.credentials.authSalt)
      await expect(unwrapWithMaster(master, F.wrapWithMaster.wrapped, F.wrapWithMaster.salt, F.wrapWithMaster.info))
        .rejects.toMatchObject({ name: 'OperationError' })
    })
  })

  describe('legacy RSA (v1)', () => {
    it('decrypts a message encrypted by the old encryptMessage', async () => {
      const p = makeProvider()
      setup(p)
      const priv = rsaPrivateFromJwk(p, F.rsa.privJwk as RsaJwk)
      expect(await decryptMessage(F.rsa.ciphertext, F.rsa.encryptedKeyForSender, priv)).toBe(F.rsa.plaintext)
      expect(await decryptMessage(F.rsa.ciphertext, F.rsa.encryptedKeyForRecipient, priv)).toBe(F.rsa.plaintext)
    })

    it('restores the key pair from the server backup wrapped by the old code (ensureKeyPair branch 2)', async () => {
      const p = makeProvider()
      const apiFetch = async (url: string) => {
        expect(url).toContain('/api/keys/me')
        return new Response(JSON.stringify({
          publicKey: JSON.stringify(F.rsa.pubJwk),
          encryptedPrivateKey: F.rsa.backup.wrapped,
          keySalt: F.rsa.backup.salt,
        }))
      }
      const platform = setup(p, { apiFetch })
      const { master } = await deriveCredentials(F.credentials.password, F.credentials.authSalt)
      const { privateKey } = await ensureKeyPair('alice', master, 'tok')
      expect(await decryptMessage(F.rsa.ciphertext, F.rsa.encryptedKeyForSender, privateKey)).toBe(F.rsa.plaintext)
      // ...and it is cached, so the next call needs neither the server nor the password
      expect(await platform.rsaKeys.load('alice')).not.toBeNull()
      const again = await ensureKeyPair('alice', null, 'tok')
      expect(await decryptMessage(F.rsa.ciphertext, F.rsa.encryptedKeyForRecipient, again.privateKey)).toBe(F.rsa.plaintext)
    })

    it('verifies the old cross-signature, and the old verifier would accept a new one', async () => {
      const p = makeProvider()
      const apiFetch = async () => new Response(JSON.stringify({
        publicKey: JSON.stringify(F.rsa.pubJwk), encryptedPrivateKey: F.rsa.backup.wrapped, keySalt: F.rsa.backup.salt,
      }))
      setup(p, { apiFetch })
      const data = fromBase64(F.rsa.signedData)
      expect(await verifyLegacySignature(F.rsa.pubJwk, data, F.rsa.signature)).toBe(true)
      expect(await verifyLegacySignature(F.rsa.pubJwk, new Uint8Array([9]), F.rsa.signature)).toBe(false)
      const { master } = await deriveCredentials(F.credentials.password, F.credentials.authSalt)
      const sig = await signWithLegacyKey(master, 'tok', data)
      // the old verifier: WebCrypto RSA-PSS, saltLength 32, SHA-256
      const key = await webcrypto.subtle.importKey('jwk', { kty: 'RSA', n: F.rsa.pubJwk.n, e: F.rsa.pubJwk.e }, { name: 'RSA-PSS', hash: 'SHA-256' }, false, ['verify'])
      expect(await webcrypto.subtle.verify({ name: 'RSA-PSS', saltLength: 32 }, key, fromBase64(sig), data)).toBe(true)
    })
  })

  describe('fingerprints and safety numbers', () => {
    it('matches the old key fingerprint, identity fingerprint and both safety numbers', async () => {
      setup(makeProvider())
      expect(await keyFingerprint(F.rsa.pubJwk)).toBe(F.fingerprints.rsa)
      expect(await computeSafetyNumber('alice', F.rsa.pubJwk, 'bob', F.rsa.pubJwk)).toBe(F.fingerprints.safety)
      expect(await identityFingerprint(new Uint8Array(33).fill(5).buffer)).toBe(F.fingerprints.idFp)
      expect(await identitySafetyNumber('alice', new Uint8Array(33).fill(5).buffer, 'bob', new Uint8Array(33).fill(6).buffer))
        .toBe(F.fingerprints.idSafety)
    }, 60_000)
  })

  describe('at-rest storage', () => {
    it('reads a Signal store and history written under a Keystore-wrapped key ("skw")', async () => {
      setup(makeProvider())
      const kv = await kvFromDump(F.atRestWrapped.kv)
      expect(await kv.keys('sig:alice:')).toContain('sig:alice:skw')
      const wrapper = fakeWrapper()
      const store = new SignalStore('alice', kv, wrapper)
      const id = await store.getIdentityKeyPair()
      expect(toBase64(new Uint8Array(id!.pubKey))).toBe(F.atRestWrapped.identity.pub)
      expect(toBase64(new Uint8Array(id!.privKey))).toBe(F.atRestWrapped.identity.priv)
      expect(await store.getDevice()).toEqual({ deviceId: 3, registrationId: 1234, nextPreKeyId: 10, signedPreKeys: [{ keyId: 2, createdAt: 99 }] })

      const history = new HistoryStore('alice', kv, wrapper)
      expect(await history.getMessages('bob')).toEqual(F.atRestWrapped.messages)
      expect((await history.getLegacyCache('bob'))[0].content).toBe('legacy')
      expect(Object.keys(await history.exportAll())).toEqual(['bob'])
    })

    it('reads data sealed under the web\'s non-extractable CryptoKey ("sk")', async () => {
      setup(makeProvider())
      const kv = await kvFromDump(F.atRestPlain.kv)
      await kv.set('sig:carol:sk', await importRawAes(fromBase64(F.atRestPlain.sigKey)))
      await kv.set('hist:carol:sk', await importRawAes(fromBase64(F.atRestPlain.histKey)))
      const store = new SignalStore('carol', kv, null)
      expect((await store.getDevice())?.registrationId).toBe(55)
      expect(toBase64(new Uint8Array((await store.getIdentityKeyPair())!.pubKey))).toBe(F.atRestWrapped.identity.pub)
      const history = new HistoryStore('carol', kv, null)
      expect(await history.getMessages('dave')).toEqual(F.atRestWrapped.messages)
    })

    it('migrates the web "sk" format to a wrapped "skw" key without losing values', async () => {
      setup(makeProvider())
      const kv = await kvFromDump(F.atRestPlain.kv)
      await kv.set('sig:carol:sk', await importRawAes(fromBase64(F.atRestPlain.sigKey)))
      const wrapper = fakeWrapper()
      const store = new SignalStore('carol', kv, wrapper)
      expect((await store.getDevice())?.registrationId).toBe(55)
      expect(await kv.get('sig:carol:sk')).toBeUndefined()
      expect(typeof (await kv.get('sig:carol:skw'))).toBe('string')
      // still readable by a cold cipher (new store instance on a new KV view)
      const cipher = new AtRestCipher(kv, 'sig:carol:', wrapper)
      const packed = await kv.get<Uint8Array>('sig:carol:device')
      expect(packed).toBeInstanceOf(Uint8Array)
      expect(JSON.parse(new TextDecoder().decode(await cipher.open('sig:carol:device', packed!))).registrationId).toBe(55)
    })
  })

  describe('App-lock password escrow (security-hardening format)', () => {
    // Built with raw WebCrypto straight from the format documented in appLockEscrow.ts:
    //   key = HKDF(PBKDF2(pw, authSalt), salt, "iris-local-escrow-v1"); AES-GCM, AAD "iris-escrow-v1:<prefix>"
    async function legacyEscrow(password: string, authSalt: string, prefix: string, raw: Uint8Array): Promise<EscrowBlob> {
      const subtle = webcrypto.subtle
      const pw = await subtle.importKey('raw', new TextEncoder().encode(password), 'PBKDF2', false, ['deriveBits'])
      const masterBits = await subtle.deriveBits({ name: 'PBKDF2', salt: fromBase64(authSalt), iterations: 600_000, hash: 'SHA-256' }, pw, 256)
      const master = await subtle.importKey('raw', masterBits, 'HKDF', false, ['deriveKey'])
      const salt = new Uint8Array(16).fill(4), iv = new Uint8Array(12).fill(6)
      const key = await subtle.deriveKey({ name: 'HKDF', hash: 'SHA-256', salt, info: new TextEncoder().encode('iris-local-escrow-v1') }, master, { name: 'AES-GCM', length: 256 }, false, ['encrypt'])
      const ct = await subtle.encrypt({ name: 'AES-GCM', iv, additionalData: new TextEncoder().encode(`iris-escrow-v1:${prefix}`) }, key, raw)
      return { v: 1, as: authSalt, salt: toBase64(salt), iv: toBase64(iv), ct: toBase64(new Uint8Array(ct)) }
    }

    it('opens an escrow written to the documented format, and writes one the format reader accepts', async () => {
      setup(makeProvider())
      const raw = new Uint8Array(32).map((_, i) => i * 7 + 1)
      const blob = await legacyEscrow('pw', F.credentials.authSalt, 'sig:alice:', raw)
      const { master } = await deriveCredentials('pw', F.credentials.authSalt)
      expect(saltOfMaster(master)).toBe(F.credentials.authSalt)
      expect(await openEscrow(master, 'sig:alice:', blob)).toEqual(raw)
      await expect(openEscrow(master, 'hist:alice:', blob)).rejects.toThrow('Wrong password')
      const mine = await sealEscrow(master, F.credentials.authSalt, 'sig:alice:', raw)
      expect(Object.keys(mine).sort()).toEqual(['as', 'ct', 'iv', 'salt', 'v'])
      expect(await openEscrow(master, 'sig:alice:', mine)).toEqual(raw)
    }, 60_000)
  })

  describe('backup', () => {
    it('opens a gzip-compressed IRB1 blob made by the old sealBackup', async () => {
      setup(makeProvider())
      const raw = fromBase64(F.backup.recoveryKeyRaw)
      expect(formatRecoveryKey(raw)).toBe(F.backup.display)
      expect(parseRecoveryKey(F.backup.display)).toEqual(raw)
      const blob = fromBase64(F.backup.blob)
      expect(new TextDecoder().decode(blob.slice(0, 4))).toBe('IRB1')
      expect(blob[4] & 1).toBe(1) // gzip flag: written by a browser with CompressionStream
      const payload = await openBackup(await importRecoveryKey(raw), 'alice', blob)
      expect(payload).toEqual(F.backup.payload)
    })

    it('refuses another account\'s name and a wrong key', async () => {
      setup(makeProvider())
      const blob = fromBase64(F.backup.blob)
      const key = await importRecoveryKey(fromBase64(F.backup.recoveryKeyRaw))
      await expect(openBackup(key, 'mallory', blob)).rejects.toMatchObject({ name: 'OperationError' })
      await expect(openBackup(await importRecoveryKey(new Uint8Array(32)), 'alice', blob)).rejects.toMatchObject({ name: 'OperationError' })
    })
  })

  describe('media and group payloads', () => {
    it('decrypts media encrypted by the old encryptMediaBytes and parses its envelope', async () => {
      setup(makeProvider())
      const pt = await decryptMediaBytes(fromBase64(F.media.ciphertext), F.media.key)
      expect(toBase64(new Uint8Array(pt))).toBe(F.media.plaintext)
      expect(parseMediaEnvelope(F.media.envelope)).toEqual({ iris: 'media', v: 1, key: F.media.key, mime: 'image/png', caption: 'cap' })
      expect(buildMediaEnvelope(F.media.key, 'image/png', 'cap')).toBe(F.media.envelope)
    })

    it('decodes an old group payload', () => {
      expect(decodeGroupPayload(F.group.wire)).toEqual({ groupId: 'g-1', inner: 'hello "team" 👋' })
    })
  })

  describe('Signal protocol', () => {
    it('decrypts a first message (PreKeyWhisperMessage) built by the old client against a restored store', async () => {
      const p = makeProvider()
      setup(p)
      // libsignal gets its crypto from the provider under test (no global WebCrypto involved)
      installLibsignalCrypto()
      try {
        const kv = await kvFromDump(F.signalWire.bobKv)
        const bob = new SignalStore('bob', kv, fakeWrapper())
        const env = F.signalWire.envelope
        expect(env.type).toBe(3)
        expect(await decryptFromDevice(bob, 'alice', 1, env.type, env.body)).toBe(F.signalWire.plaintext)
      } finally {
        setWebCrypto(webcrypto as unknown as Crypto)
      }
    })
  })
})

describe('message shape', () => {
  it('the fixture messages are plain ChatMessages', () => {
    const m = F.atRestWrapped.messages as ChatMessage[]
    expect(m.map(x => x.id)).toEqual([1, 2])
  })
})
